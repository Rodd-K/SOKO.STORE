-- ---------- Tables ----------
create table public.categories (
  slug text primary key,
  name text not null
);

create table public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null references public.categories(slug),
  price integer not null check (price >= 0),
  original_price integer check (original_price is null or original_price >= 0),
  stock integer not null default 0 check (stock >= 0),
  rating numeric(2,1) not null default 0,
  image text,
  description text,
  is_new boolean not null default false,
  created_at timestamptz not null default now()
);

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  phone text,
  county text,
  town text,
  is_admin boolean not null default false,
  created_at timestamptz not null default now()
);

create table public.orders (
  id bigint generated by default as identity (start with 1001) primary key,
  user_id uuid not null references auth.users(id),
  status text not null default 'Pending'
    check (status in ('Pending','Confirmed','Processing','Shipped','Delivered','Cancelled')),
  payment_method text not null check (payment_method in ('cod','mpesa','card')),
  full_name text not null,
  phone text not null,
  county text not null,
  town text not null,
  address text not null,
  subtotal integer not null,
  delivery_fee integer not null,
  total integer not null,
  created_at timestamptz not null default now()
);

create table public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  product_id bigint not null references public.products(id),
  name text not null,        -- snapshot of the name at purchase time
  price integer not null,    -- snapshot of the price at purchase time
  quantity integer not null check (quantity > 0)
);

create table public.wishlist (
  user_id uuid not null references auth.users(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, product_id)
);

create index on public.products (category);
create index on public.orders (user_id, created_at desc);
create index on public.order_items (order_id);

-- ---------- Auto-create a profile when someone signs up ----------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, phone)
  values (
    new.id,
    new.raw_user_meta_data ->> 'full_name',
    new.raw_user_meta_data ->> 'phone'
  );
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ---------- Place an order (server-side: real prices, real stock) ----------
-- p_items:    [{"product_id": 2, "quantity": 1}, ...]
-- p_delivery: {"full_name":"","phone":"","county":"","town":"","address":""}
create or replace function public.place_order(
  p_items jsonb,
  p_delivery jsonb,
  p_payment text
)
returns bigint
language plpgsql
security definer set search_path = ''
as $$
declare
  v_user uuid := auth.uid();
  v_order_id bigint;
  v_subtotal integer := 0;
  v_fee constant integer := 300;
  v_item jsonb;
  v_product public.products%rowtype;
  v_qty integer;
begin
  if v_user is null then
    raise exception 'You must be logged in to place an order';
  end if;
  if p_items is null or jsonb_array_length(p_items) = 0 then
    raise exception 'Cart is empty';
  end if;

  insert into public.orders
    (user_id, payment_method, full_name, phone, county, town, address,
     subtotal, delivery_fee, total)
  values
    (v_user, p_payment,
     p_delivery ->> 'full_name', p_delivery ->> 'phone',
     p_delivery ->> 'county', p_delivery ->> 'town', p_delivery ->> 'address',
     0, v_fee, 0)
  returning id into v_order_id;

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_qty := (v_item ->> 'quantity')::integer;
    if v_qty is null or v_qty < 1 then
      raise exception 'Invalid quantity';
    end if;

    -- lock the row so two buyers can't take the last unit at once
    select * into v_product
    from public.products
    where id = (v_item ->> 'product_id')::bigint
    for update;

    if not found then
      raise exception 'Product % not found', v_item ->> 'product_id';
    end if;
    if v_product.stock < v_qty then
      raise exception 'Not enough stock for %', v_product.name;
    end if;

    update public.products set stock = stock - v_qty where id = v_product.id;

    insert into public.order_items (order_id, product_id, name, price, quantity)
    values (v_order_id, v_product.id, v_product.name, v_product.price, v_qty);

    v_subtotal := v_subtotal + v_product.price * v_qty;
  end loop;

  update public.orders
  set subtotal = v_subtotal, total = v_subtotal + v_fee
  where id = v_order_id;

  return v_order_id;
end;
$$;

revoke all on function public.place_order(jsonb, jsonb, text) from public, anon;
grant execute on function public.place_order(jsonb, jsonb, text) to authenticated;

-- ---------- Row Level Security ----------
alter table public.categories  enable row level security;
alter table public.products    enable row level security;
alter table public.profiles    enable row level security;
alter table public.orders      enable row level security;
alter table public.order_items enable row level security;
alter table public.wishlist    enable row level security;

-- Catalogue is public read-only
create policy "categories are public" on public.categories for select using (true);
create policy "products are public"   on public.products   for select using (true);

-- Profiles: users read/update only their own row (cannot make themselves admin)
create policy "read own profile" on public.profiles
  for select using (auth.uid() = id);
create policy "update own profile" on public.profiles
  for update using (auth.uid() = id) with check (auth.uid() = id and is_admin = false);

-- Orders: users can only READ their own. Creation happens only via place_order().
create policy "read own orders" on public.orders
  for select using (auth.uid() = user_id);
create policy "read own order items" on public.order_items
  for select using (
    exists (select 1 from public.orders o
            where o.id = order_id and o.user_id = auth.uid())
  );

-- Wishlist: fully own-row
create policy "own wishlist" on public.wishlist
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

